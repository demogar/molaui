/**
 * The Markdown an agent reads, besides llms.txt and llms-full.txt: one file
 * per topic and one Markdown twin per docs page. scripts/export-manifest.ts
 * gathers the data (exports, props, stories, guidance) and calls these; it
 * writes and checks the results with everything else it generates.
 *
 *   llms-components.txt   every component: usage, props, accessibility,
 *                         anatomy and where it is used
 *   llms-tokens.txt       every token with its role and its value in each
 *                         theme, from the resolver the Tokens page uses
 *   llms-patterns.txt     the whole screens, with their parts and states
 *   docs/ai/md/<id>.md    the Markdown twin of the docs page `<id>`, served
 *                         by Storybook at `md/<id>.md` (.storybook/main.ts)
 *
 * Why twins and not only llms-full.txt: an agent that has been sent a docs
 * link wants that page, not 240 KB. A twin keeps the URL shape the reader
 * already has (the page id) so it can be found without an index.
 *
 * MDX pages are converted from their source: prose and code blocks are kept,
 * imports and comments dropped, and a JSX block either rendered from the same
 * data it renders on the page (the token table, swatches, decision records,
 * the changelog) or replaced by a note that names it and links the page. A
 * block is never silently dropped, so a reader knows when the page shows more.
 */
