/* ── MDX pages ──────────────────────────────────────────────────────── */

/**
 * Pages whose Markdown is already a file in the repository. That file is
 * served as the twin, as is (.storybook/main.ts maps it into md/), instead of
 * being generated. The changelog is CHANGELOG.md, which release-please
 * rewrites in every release pull request: a generated copy would be stale on
 * main the moment a release merged, and fail manifest:check there.
 */
export const SERVED_AS_IS: Record<string, string> = { 'Mola UI/Changelog': 'CHANGELOG.md' }

export interface MdxPage {
  file: string
  title: string
}

/** Every MDX page with a `<Meta title>`, as Storybook indexes them. */
export function mdxPages(): MdxPage[] {
  const walk = (dir: string): string[] =>
    readdirSync(resolve(root, dir), { withFileTypes: true }).flatMap((d) =>
      d.isDirectory() ? walk(`${dir}/${d.name}`) : d.name.endsWith('.mdx') ? [`${dir}/${d.name}`] : [],
    )
  return walk('src')
    .sort()
    .flatMap((file) => {
      const title = read(file).match(/<Meta\s+title="([^"]+)"/)?.[1]
      return title ? [{ file, title }] : []
    })
}

/** The ADR files, by number, with the page each one is rendered on. */
function decisions(pages: MdxPage[]) {
  const files = readdirSync(resolve(root, 'docs/adr')).filter((f) => /^\d{4}-.*\.md$/.test(f)).sort()
  return files.map((f) => {
    const number = f.slice(0, 4)
    const text = read(`docs/adr/${f}`)
    const page = pages.find((p) => read(p.file).includes(`<DecisionRecord number="${number}"`))
    return { number, file: `docs/adr/${f}`, text, heading: text.match(/^#\s+(.+)$/m)?.[1] ?? number, page: page?.title }
  })
}

/** From `<` at `start`, the index just past the end of the JSX element. */
function elementEnd(text: string, start: number): number {
  const name = /^<([A-Za-z][\w.]*)/.exec(text.slice(start))![1]!
  let depth = 0
  let quote: string | null = null
  let i = start + name.length + 1
  for (; i < text.length; i++) {
    const ch = text[i]!
    if (quote) {
      if (ch === quote && text[i - 1] !== '\\') quote = null
      continue
    }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch
    else if (ch === '{') depth++
    else if (ch === '}') depth--
    else if (depth === 0 && ch === '/' && text[i + 1] === '>') return i + 2
    else if (depth === 0 && ch === '>') break
  }
  // An element with children: find its matching close, counting nested opens.
  const open = new RegExp(`<${name.replace('.', '\\.')}[\\s>]`, 'g')
  const close = `</${name}>`
  let nest = 1
  let pos = i + 1
  while (nest > 0) {
    const nextClose = text.indexOf(close, pos)
    if (nextClose < 0) return text.length
    open.lastIndex = pos
    const nextOpen = open.exec(text)
    if (nextOpen && nextOpen.index < nextClose) {
      nest++
      pos = nextOpen.index + 1
    } else {
      nest--
      pos = nextClose + close.length
    }
  }
  return pos
}

interface MdxContext {
  site: string
  pages: MdxPage[]
  description: string
}

function renderBlock(block: string, page: MdxPage, ctx: MdxContext): string {
  const name = /^<([A-Za-z][\w.]*)/.exec(block)![1]!
  const attr = (key: string) => new RegExp(`${key}="([^"]+)"`).exec(block)?.[1]
  const pageUrl = `${ctx.site}?path=/docs/${docsId(page.title)}`
  switch (name) {
    case 'Meta':
      return ''
    case 'Hero':
      return `# Mola UI\n\n> ${ctx.description}`
    case 'TokenTable':
      return tokenTable()
    case 'ScopeTable':
      return scopesTable()
    case 'SwatchGrid': {
      const rows = [...block.matchAll(/token: '(--[a-z0-9-]+)', role: '([^']*)'(?:, on: '(--[a-z0-9-]+)')?/g)]
      return [
        '| Token | Role | Light | Dark |',
        '| --- | --- | --- | --- |',
        ...rows.map(([, token, role]) => {
          const row = TOKEN_ROWS.find((r) => r.name === token)
          return `| \`${token}\` | ${cell(role!)} | \`${row?.light ?? ''}\` | \`${row?.dark ?? ''}\` |`
        }),
      ].join('\n')
    }
    case 'PairingTable': {
      const pairs = [...block.matchAll(/\['(--[a-z0-9-]+)', '(--[a-z0-9-]+)'\]/g)]
      const ratio = (fg: string, bg: string, theme: ThemeName) => {
        const a = resolved(fg, theme)
        const b = resolved(bg, theme)
        return a && b ? contrast(a, b).toFixed(2) : 'n/a'
      }
      return [
        'Contrast ratios, computed from tokens.css:',
        '',
        '| Text | Ground | Light | Dark |',
        '| --- | --- | --- | --- |',
        ...pairs.map(([, fg, bg]) => `| \`${fg}\` | \`${bg}\` | ${ratio(fg!, bg!, 'light')} | ${ratio(fg!, bg!, 'dark')} |`),
      ].join('\n')
    }
    case 'DecisionRecord': {
      const d = decisions(ctx.pages).find((x) => x.number === attr('number'))
      return d ? d.text.trim() : ''
    }
    case 'DecisionIndex':
      return list(
        decisions(ctx.pages).map((d) => {
          const status = d.text.match(/^\s*(?:-\s*)?\**Status\**:?\**\s*(.+)$/im)?.[1]?.trim()
          return `[${d.heading}](${d.page ? twinUrl(ctx.site, d.page) : d.file})${status ? ` (${status.replace(/\*/g, '')})` : ''}`
        }),
      )
    case 'DecisionsBehind':
      return `The decisions behind this page are architecture decision records: see [Decisions](${twinUrl(ctx.site, 'Decisions/All decisions')}).`
    default: {
      const alts = [...block.matchAll(/alt="([^"]+)"/g)].map((m) => m[1])
      const what = /^[A-Z]/.test(name) ? `an interactive \`${name}\` block` : 'a block of illustrations'
      return `> Not included in the Markdown version: ${what}. See it on the page: ${pageUrl}${alts.length ? `\n>\n${alts.map((a) => `> - Image: ${a}`).join('\n')}` : ''}`
    }
  }
}

/** An MDX page as Markdown: prose and code kept, imports and comments dropped, JSX rendered or noted. */
export function mdxTwin(page: MdxPage, ctx: MdxContext) {
  const text = read(page.file)
  const out: string[] = []
  let i = 0
  let fence: string | null = null
  while (i < text.length) {
    const lineEnd = text.indexOf('\n', i) < 0 ? text.length : text.indexOf('\n', i)
    const line = text.slice(i, lineEnd)
    const marker = /^\s*(```|~~~)/.exec(line)?.[1]
    if (fence) {
      out.push(line)
      if (marker === fence) fence = null
      i = lineEnd + 1
      continue
    }
    if (marker) {
      fence = marker
      out.push(line)
      i = lineEnd + 1
      continue
    }
    if (/^(import|export)\s/.test(line)) {
      // A statement runs to its `from '…'`, or to the next blank line.
      let end = lineEnd
      if (!/from\s+['"]|^import\s+['"]/.test(line)) {
        const from = text.slice(i).search(/from\s+['"][^'"]+['"];?\s*\n|\n\s*\n/)
        end = from < 0 ? text.length : text.indexOf('\n', i + from + 1)
      }
      i = (end < 0 ? text.length : end) + 1
      continue
    }
    if (/^\s*\{\/\*/.test(line)) {
      const close = text.indexOf('*/}', i)
      const end = text.indexOf('\n', close)
      i = end < 0 ? text.length : end + 1
      continue
    }
    if (/^\s*<[A-Za-z]/.test(line)) {
      const start = i + line.search(/</)
      const end = elementEnd(text, start)
      out.push(renderBlock(text.slice(start, end), page, ctx))
      const next = text.indexOf('\n', end)
      i = next < 0 ? text.length : next + 1
      continue
    }
    out.push(absolute(line, ctx.site))
    i = lineEnd + 1
  }
  return tidy(`${twinHeader(ctx.site, page.title, page.file)}${out.join('\n')}`)
}

/** One blank line between blocks, one newline at the end. */
function tidy(text: string) {
  return `${text.replace(/\n{3,}/g, '\n\n').trim()}\n`
}
