/**
 * tokens + manifest -> the plugin's data, its code.js and the component map.
 *
 * code.js is the plugin's runtime (plugin.ts) transpiled on its own with the
 * repo's pinned TypeScript, wrapped with the data inlined. A Figma plugin's
 * main code is one file with no module loader, and plugin.ts imports nothing
 * but types, so a bundler would only add a dependency and a second source of
 * nondeterminism; `transpileModule` is enough, and its output is the same
 * byte for byte on every machine with the same TypeScript, which is what
 * lets the drift gate compare the committed file.
 *
 * Target ES2017: Figma's plugin sandbox has historically lagged the browser
 * on newer syntax (object spread, optional chaining), and lowering them costs
 * nothing here.
 */
import ts from 'typescript'

import { buildComponents, type ComponentMap, type Manifest } from './components'
import { buildIcons } from './icons'
import type { KitData, NodeSpec } from './spec'
import { buildTokens, type Tokens } from './tokens'

export const PAGE = 'Mola UI'

export interface Kit {
  data: KitData
  map: ComponentMap
}

export function buildKit(tokens: Tokens, manifest: Manifest): Kit {
  const { collections, effectStyles } = buildTokens(tokens)
  const { components, map } = buildComponents(manifest, collections)

  const used = new Map<string, { family: string; style: string; required: boolean }>()
  const walk = (node: NodeSpec) => {
    if (node.kind === 'text') used.set(`${node.text.family.name}/${node.text.style}`, { family: node.text.family.name, style: node.text.style, required: true })
    if (node.kind === 'frame') node.children.forEach(walk)
  }
  for (const c of components) for (const v of c.variants) walk(v.root)
  // The other two voices are loaded too, so a file missing them hears about
  // it now rather than when the first prose component is drawn.
  for (const v of collections.find((c) => c.name === 'Scale')!.variables) {
    if (v.type !== 'STRING' || !v.name.startsWith('font-')) continue
    const family = String(v.values[0])
    if (![...used.values()].some((f) => f.family === family)) used.set(`${family}/Regular`, { family, style: 'Regular', required: false })
  }

  return {
    data: { page: PAGE, fonts: [...used.values()], collections, effectStyles, icons: buildIcons(), components },
    map,
  }
}

/** The plugin's code.js: the transpiled runtime, then `main(figma, DATA)`. */
export function renderCode(pluginSource: string, data: KitData): string {
  const { outputText } = ts.transpileModule(pluginSource, {
    compilerOptions: { target: ts.ScriptTarget.ES2017, module: ts.ModuleKind.CommonJS, removeComments: false, newLine: ts.NewLineKind.LineFeed },
    fileName: 'plugin.ts',
  })
  return [
    '// Generated by scripts/export-figma.ts from figma/src/plugin.ts, tokens/mola.tokens.json and',
    '// docs/ai/components.json. Do not edit: run `npm run figma`.',
    '(function () {',
    'var exports = {};',
    outputText.trim(),
    `var DATA = ${JSON.stringify(data)};`,
    'exports.main(figma, DATA);',
    '})();',
    '',
  ].join('\n')
}

export const renderMap = (map: ComponentMap) => `${JSON.stringify(map, null, 2)}\n`
