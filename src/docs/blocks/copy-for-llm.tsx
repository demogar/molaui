import { Check, Copy, TriangleAlert } from 'lucide-react'
import * as React from 'react'

import { Button } from '../../components/button'
import { docsId } from '../usage/links'
import { titleName } from './usage'

type CopyState = 'idle' | 'copied' | 'failed'

const LOOK: Record<CopyState, { Glyph: typeof Copy; label: string }> = {
  idle: { Glyph: Copy, label: 'Copy for LLM' },
  copied: { Glyph: Check, label: 'Copied' },
  failed: { Glyph: TriangleAlert, label: 'Not copied' },
}

/** How long "Copied" stays on the button before it offers to copy again. */
const RESET_MS = 4000

/**
 * Copies the page's Markdown twin (docs/ai/md/<id>.md, served at md/<id>.md
 * and generated by scripts/export-manifest.ts) so a reader can hand the page
 * to a model without scraping it.
 *
 * The text is fetched, not bundled: a hundred twins in the docs bundle would
 * be paid for by every reader to serve the few who copy. The fetch happens
 * inside the click, so the clipboard write is handed a promise
 * (`ClipboardItem`): Safari drops a `writeText` that runs after an `await`,
 * because by then the click no longer counts as a user gesture.
 * `writeText` is only the fallback for a browser without `ClipboardItem`.
 *
 * The button says what happened with a glyph and a word, never colour alone,
 * and a polite status says it again for a screen reader, since a button's
 * changed label is not announced while focus stays on it.
 */
export function CopyForLlm({ title }: { title: string }) {
  const href = `md/${docsId(title)}.md`
  const name = titleName(title)
  const hintId = React.useId()
  const [state, setState] = React.useState<CopyState>('idle')
  const [message, setMessage] = React.useState('')

  React.useEffect(() => {
    if (state === 'idle') return
    const timer = window.setTimeout(() => setState('idle'), RESET_MS)
    return () => window.clearTimeout(timer)
  }, [state])

  async function copy() {
    const text = fetch(href).then((response) => {
      if (!response.ok) throw new Error(`${response.status}`)
      return response.text()
    })
    try {
      if (typeof ClipboardItem !== 'undefined' && navigator.clipboard?.write) {
        const blob = text.then((markdown) => new Blob([markdown], { type: 'text/plain' }))
        await navigator.clipboard.write([new ClipboardItem({ 'text/plain': blob })])
      } else {
        await navigator.clipboard.writeText(await text)
      }
      setState('copied')
      setMessage(`Copied the ${name} page as Markdown.`)
    } catch {
      setState('failed')
      setMessage(`Could not copy the ${name} page. Open it as Markdown and copy it from there.`)
    }
  }

  const { Glyph, label } = LOOK[state]
  return (
    <div data-copy-for-llm className="sb-unstyled not-prose my-4 flex flex-wrap items-center gap-x-3 gap-y-2 font-ui text-sm text-ink">
      <Button
        variant="secondary"
        size="sm"
        data-state={state}
        aria-describedby={hintId}
        icon={<Glyph strokeWidth={2.5} />}
        onClick={copy}
      >
        {label}
      </Button>
      <a href={href} target="_blank" rel="noreferrer" className="text-ink underline underline-offset-2">
        Open as Markdown
      </a>
      <span id={hintId} className="text-ink-muted">
        This page as Markdown, to paste into a chat or an agent&rsquo;s context.
      </span>
      <span role="status" className="sr-only">
        {message}
      </span>
    </div>
  )
}
