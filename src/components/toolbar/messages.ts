/** The words ToolbarOverflow says on its own. */
export interface ToolbarOverflowMessages {
  /** The visible label of the menu button that collects what does not fit. */
  more: string
  /** That button's accessible name, when `moreLabel` is not set. */
  moreActions: string
}

export const toolbarOverflowMessages: ToolbarOverflowMessages = {
  more: 'More',
  moreActions: 'More actions',
}
